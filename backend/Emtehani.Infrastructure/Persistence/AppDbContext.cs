  b.Entity<AppUser>().HasIndex(x=>x.Email).IsUnique();
  b.Entity<AppUser>().Property(x=>x.StudentCode).HasMaxLength(12);
  b.Entity<AppUser>().Property(x=>x.Stage).HasMaxLength(32);
  b.Entity<AppUser>().Property(x=>x.Grade).HasMaxLength(64);
  b.Entity<AppUser>().Property(x=>x.NormalizedName).HasMaxLength(256);
  b.Entity<AppUser>().Property(x=>x.StudentPhone).HasMaxLength(20);
  b.Entity<AppUser>().Property(x=>x.ParentPhone).HasMaxLength(20);
  b.Entity<AppUser>().Property(x=>x.RegistrationSource).HasMaxLength(24);  var studentNameFilter = npgsql ? "\"Role\" = 'Student' AND \"NormalizedName\" <> ''" : "[Role] = 'Student' AND [NormalizedName] <> ''";
  b.Entity<AppUser>().HasIndex(x=>x.NormalizedName).IsUnique().HasDatabaseName("IX_Users_NormalizedName_Student").HasFilter(studentNameFilter);
  var studentPhoneFilter = npgsql ? "\"StudentPhone\" IS NOT NULL AND \"StudentPhone\" <> ''" : "[StudentPhone] IS NOT NULL AND [StudentPhone] <> ''";
  b.Entity<AppUser>().HasIndex(x=>x.StudentPhone).IsUnique().HasDatabaseName("IX_Users_StudentPhone").HasFilter(studentPhoneFilter);
  b.Entity<AppUser>().HasIndex(x=>x.ParentPhone);
  b.Entity<Exam>().Property(x=>x.Stage).HasMaxLength(32);
  b.Entity<Exam>().Property(x=>x.Grade).HasMaxLength(64);
  b.Entity<Exam>().Property(x=>x.ResultsReleaseMode).HasMaxLength(32);
  b.Entity<Exam>().Property(x=>x.AcademicYear).HasMaxLength(16);
  b.Entity<Exam>().HasIndex(x=>x.AcademicYear);
  b.Entity<AppUser>().Property(x=>x.RefreshTokenHash).HasMaxLength(64);
  b.Entity<AppUser>().HasIndex(x=>x.RefreshTokenHash);
  var studentCodeFilter = npgsql ? "\"StudentCode\" <> ''" : "[StudentCode] <> ''";
  b.Entity<AppUser>().HasIndex(x=>x.StudentCode).IsUnique().HasDatabaseName("IX_Users_StudentCode").HasFilter(studentCodeFilter);
  b.Entity<Exam>().HasMany(x=>x.Questions).WithOne(x=>x.Exam).HasForeignKey(x=>x.ExamId).OnDelete(DeleteBehavior.Cascade);
  b.Entity<Exam>().HasMany(x=>x.Participants).WithOne(x=>x.Exam).HasForeignKey(x=>x.ExamId).OnDelete(DeleteBehavior.Cascade);
  b.Entity<ExamParticipant>().HasOne(x=>x.Student).WithMany().HasForeignKey(x=>x.StudentId).OnDelete(DeleteBehavior.Cascade);
  b.Entity<ExamParticipant>().HasIndex(x=>new{x.ExamId,x.StudentId}).IsUnique();
  var participantCodeFilter = npgsql ? "\"Code\" <> ''" : "[Code] <> ''";
  b.Entity<ExamParticipant>().HasIndex(x=>x.Code).IsUnique().HasFilter(participantCodeFilter);
  b.Entity<Exam>().HasIndex(x=>x.JoinCode).IsUnique();
  b.Entity<Submission>().HasOne(x=>x.Student).WithMany().HasForeignKey(x=>x.StudentId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<Submission>().HasOne(x=>x.Exam).WithMany().HasForeignKey(x=>x.ExamId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<Submission>().HasMany(x=>x.Answers).WithOne(x=>x.Submission).HasForeignKey(x=>x.SubmissionId).OnDelete(DeleteBehavior.Cascade);
  var inProgressFilter = npgsql ? "\"Status\" = 'InProgress'" : "[Status] = 'InProgress'";
  b.Entity<Submission>().HasIndex(x=>new{x.ExamId,x.StudentId}).HasDatabaseName("IX_Submissions_Exam_Student_InProgress").HasFilter(inProgressFilter).IsUnique();
  b.Entity<Submission>().Property(x=>x.StageAtAttempt).HasMaxLength(32);
  b.Entity<Submission>().Property(x=>x.GradeAtAttempt).HasMaxLength(64);
  b.Entity<Submission>().Property(x=>x.AcademicYearAtAttempt).HasMaxLength(16);
  b.Entity<SubmissionAnswer>().HasOne(x=>x.Question).WithMany().HasForeignKey(x=>x.QuestionId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<SubmissionAnswer>().HasIndex(x=>new{x.SubmissionId,x.QuestionId}).IsUnique();
  b.Entity<TeacherStudentRequest>().HasOne(x=>x.Teacher).WithMany().HasForeignKey(x=>x.TeacherId).OnDelete(DeleteBehavior.Cascade);
  b.Entity<TeacherStudentRequest>().HasOne(x=>x.Student).WithMany().HasForeignKey(x=>x.StudentId).OnDelete(DeleteBehavior.NoAction);
  b.Entity<TeacherStudentRequest>().HasIndex(x=>new{x.TeacherId,x.StudentId}).IsUnique();
  b.Entity<TeacherStudentRequest>().HasIndex(x=>x.StudentId);
  b.Entity<TeacherStudentRequest>().Property(x=>x.InitiatedBy).HasMaxLength(24);
  b.Entity<TeacherStudentExamBan>().HasOne(x=>x.Exam).WithMany().HasForeignKey(x=>x.ExamId).OnDelete(DeleteBehavior.Cascade);
  b.Entity<TeacherStudentExamBan>().HasOne<AppUser>().WithMany().HasForeignKey(x=>x.TeacherId).OnDelete(DeleteBehavior.Cascade);
  b.Entity<TeacherStudentExamBan>().HasOne<AppUser>().WithMany().HasForeignKey(x=>x.StudentId).OnDelete(DeleteBehavior.NoAction);
  b.Entity<TeacherStudentExamBan>().HasIndex(x=>new{x.ExamId,x.StudentId}).IsUnique().HasDatabaseName("IX_TeacherStudentExamBans_ExamId_StudentId");
  b.Entity<TeacherStudentExamBan>().HasIndex(x=>new{x.TeacherId,x.StudentId}).HasDatabaseName("IX_TeacherStudentExamBans_TeacherId_StudentId");
  b.Entity<StudentAcademicChange>().HasOne(x=>x.Student).WithMany().HasForeignKey(x=>x.StudentId).OnDelete(DeleteBehavior.Cascade);
  b.Entity<StudentAcademicChange>().HasIndex(x=>new{x.StudentId,x.ChangedAtUtc});
  b.Entity<StudentAcademicChange>().Property(x=>x.PreviousStage).HasMaxLength(32);
  b.Entity<StudentAcademicChange>().Property(x=>x.PreviousGrade).HasMaxLength(64);
  b.Entity<StudentAcademicChange>().Property(x=>x.NewStage).HasMaxLength(32);
  b.Entity<StudentAcademicChange>().Property(x=>x.NewGrade).HasMaxLength(64);
  b.Entity<StudentAcademicChange>().Property(x=>x.ChangedByRole).HasMaxLength(24);
  b.Entity<StudentAcademicChange>().Property(x=>x.Source).HasMaxLength(24);
  b.Entity<SubscriptionPlan>().HasIndex(x=>x.Code).IsUnique();
  b.Entity<SubscriptionPlan>().Property(x=>x.Code).HasMaxLength(48);
  b.Entity<SubscriptionPlan>().Property(x=>x.Name).HasMaxLength(120);
  b.Entity<SubscriptionPlan>().Property(x=>x.Description).HasMaxLength(500);
  b.Entity<TeacherSubscription>().HasOne(x=>x.Teacher).WithMany().HasForeignKey(x=>x.TeacherId).OnDelete(DeleteBehavior.Cascade);
  b.Entity<TeacherSubscription>().HasOne(x=>x.Plan).WithMany().HasForeignKey(x=>x.PlanId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<TeacherSubscription>().HasIndex(x=>x.TeacherId).HasDatabaseName("IX_TeacherSubscriptions_TeacherId");
  b.Entity<TeacherSubscription>().Property(x=>x.Status).HasMaxLength(24);
  b.Entity<SystemSetting>().HasKey(x=>x.Key);
  b.Entity<SystemSetting>().Property(x=>x.Key).HasMaxLength(120);
  b.Entity<TeacherStudentInvitation>().HasOne(x=>x.Teacher).WithMany().HasForeignKey(x=>x.TeacherId).OnDelete(DeleteBehavior.Cascade);
  b.Entity<TeacherStudentInvitation>().HasIndex(x=>x.Token).IsUnique();
  b.Entity<TeacherStudentInvitation>().HasIndex(x=>new{x.TeacherId,x.StudentPhone});
  b.Entity<TeacherStudentInvitation>().Property(x=>x.StudentName).HasMaxLength(200);
  b.Entity<TeacherStudentInvitation>().Property(x=>x.StudentPhone).HasMaxLength(20);
  b.Entity<TeacherStudentInvitation>().Property(x=>x.ParentPhone).HasMaxLength(20);
  b.Entity<TeacherStudentInvitation>().Property(x=>x.Stage).HasMaxLength(32);
  b.Entity<TeacherStudentInvitation>().Property(x=>x.Grade).HasMaxLength(64);
  b.Entity<TeacherStudentInvitation>().Property(x=>x.Token).HasMaxLength(64);
  b.Entity<TeacherStudentInvitation>().Property(x=>x.Status).HasMaxLength(24);
 }
}
